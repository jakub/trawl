//! `design-cards` — emit static HTML preview cards from fleet-ui's
//! class contracts, for iteration on claude.ai/design.
//!
//! fleet-ui components are wasm32-gated CSR, so there is no native
//! render-to-string: each snippet emitter below mirrors the markup its
//! leptos counterpart renders (the `view!` blocks under
//! `crates/fleet-ui/src/`). When a component's DOM changes, the emitter
//! here must change with it — the cards are DERIVED artifacts,
//! regenerated by `cargo xtask design-cards`, never hand-edited.
//!
//! Each card is one self-contained HTML file: `@dsCard` marker on line
//! one, `fleet-ui.css` inlined, and the same snippet stamped into a
//! light pane and a dark pane side by side. The theme split works
//! because fleet-ui.css scopes all color tokens under bare
//! `[data-theme=…]` attribute selectors — re-declaring the attribute on
//! a `<section>` re-scopes every token beneath it. Gallery-only chrome
//! uses a `ds-` class prefix so it can never collide with fleet
//! selectors.

// The whole module builds HTML by mapping snippet emitters over slices;
// the fold+write! shape clippy prefers buries the templates in plumbing.
#![allow(clippy::format_collect)]

use std::fs;
use std::path::Path;
use std::process::ExitCode;

/// Google Fonts links, same families/weights as the consuming apps
/// (`crates/trawl-web-ui/index.html`) — fleet-ui.css declares the
/// families but deliberately does not load them.
const FONT_LINKS: &str = r#"<link rel="preconnect" href="https://fonts.googleapis.com"/>
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin/>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=JetBrains+Mono:wght@400;500;600;700&display=swap"/>"#;

